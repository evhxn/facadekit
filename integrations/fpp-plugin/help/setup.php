<h3>FacadeKit Projectors</h3>
<p>Add each projector with the address and port of its PJLink service (4352) and, if PJLink
authentication is on in the projector's menu, its PJLink password. Press <b>Test</b> to read its
state. <b>All on</b> and <b>All off</b> switch every projector at once.</p>
<p>In a playlist, use the FPP Commands <i>FacadeKit Projectors On</i> (in the lead-in, with
<i>Wait until ready</i> when the picture must be there from the first second),
<i>FacadeKit Projectors Off</i>, <i>FacadeKit Select Input</i> and <i>FacadeKit Status Snapshot</i>.
The same commands work in the scheduler and in presets.</p>
<p>To pair FacadeKit, press <b>Create pairing token</b> and paste the token into FacadeKit's
Falcon Player panel. The token is shown once; create a new one if it is lost.</p>

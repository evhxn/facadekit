"""Sample projects: a simulated house with a short show, no hardware and no media files.

`create_sample(folder, ...)` scans the simulator's house (`sim/scene.py`) exactly as
`facadekit sim e2e` does, finds the garage door on the scan, adds the two windows from the
simulated house's layout, and lays out a 12 s timeline made only of built-in effects and
pictures drawn here (title card, a pumpkin or a snowflake). Everything is generated by this
code, so a sample may be rendered and projected anywhere (docs/06: sample content must be
CC0 or CC BY 4.0).

The house is simulated: the scan, the door and the windows do not describe anyone's real
house. The project name and the title card both say so.
"""

from __future__ import annotations

import math
from collections.abc import Callable
from pathlib import Path
from typing import Literal

import cv2
import numpy as np

from facadekit.calib.pipeline import run_calibration
from facadekit.errors import INTERNAL, FkError
from facadekit.geom.homography import estimate_aspect
from facadekit.ids import new_id
from facadekit.media.probe import make_thumbnail
from facadekit.models.calibration import CalibSettings
from facadekit.models.project import (
    CANVAS,
    Asset,
    Clip,
    Generator,
    Project,
    ProjectorSpec,
    Surface,
    Timeline,
    Track,
)
from facadekit.sim.devices import SimCamera, SimDisplay
from facadekit.sim.e2e import detect_door_quad
from facadekit.sim.scene import default_scene
from facadekit.store.project_store import SUBFOLDERS, save_project_dir

Theme = Literal["halloween", "winter"]
THEMES: tuple[Theme, ...] = ("halloween", "winter")
THEME_NAMES: dict[Theme, str] = {"halloween": "Halloween", "winter": "Winter"}
SAMPLE_DURATION_MS = 12000

Progress = Callable[[float, str], None]
Cancel = Callable[[], bool]
Point = tuple[float, float]


def sample_name(theme: Theme) -> str:
    return f"Sample: {THEME_NAMES[theme]} (simulated house)"


def _write_png(project_dir: Path, image: np.ndarray, original: str) -> Asset:
    asset_id = new_id("ast")
    rel = f"media/{asset_id}.png"
    if not cv2.imwrite(str(project_dir / rel), image):
        raise FkError(INTERNAL, f"Could not write the sample picture {original}")
    # The media library shows a thumbnail, made the same way as for an uploaded picture.
    make_thumbnail(project_dir / rel, "image", project_dir / "media" / f"{asset_id}.thumb.jpg")
    h, w = image.shape[:2]
    return Asset(
        id=asset_id, kind="image", filename=rel, original_name=original, width=w, height=h,
        duration_ms=None, fps=None, has_alpha=image.ndim == 3 and image.shape[2] == 4,
    )  # fmt: skip


def _centered_text(
    img: np.ndarray, text: str, y: int, scale: float, color: tuple[int, ...]
) -> None:
    font = cv2.FONT_HERSHEY_DUPLEX
    thick = max(1, round(scale * 2))
    (tw, _), _ = cv2.getTextSize(text, font, scale, thick)
    x = (img.shape[1] - tw) // 2
    cv2.putText(img, text, (x, y), font, scale, color, thick, cv2.LINE_AA)


def title_card(theme: Theme) -> np.ndarray:
    """Black 960x540 card: the theme, and that this is a simulated house."""
    img = np.zeros((540, 960, 3), np.uint8)
    accent = (0, 140, 255) if theme == "halloween" else (255, 220, 160)
    cv2.rectangle(img, (24, 24), (935, 515), accent, 4, cv2.LINE_AA)
    _centered_text(img, "FacadeKit sample", 170, 2.0, (255, 255, 255))
    _centered_text(img, THEME_NAMES[theme], 290, 2.6, accent)
    _centered_text(img, "Simulated house - no projector needed", 420, 1.1, (200, 200, 200))
    return img


def pumpkin() -> np.ndarray:
    """A jack-o'-lantern on black, 640x480, drawn with shapes."""
    img = np.zeros((480, 640, 3), np.uint8)
    for dx, rx in ((-120, 130), (120, 130), (-55, 120), (55, 120), (0, 120)):
        cv2.ellipse(img, (320 + dx, 270), (rx, 170), 0, 0, 360, (0, 110, 235), -1, cv2.LINE_AA)
    cv2.rectangle(img, (305, 60), (335, 110), (40, 110, 60), -1)
    glow = (60, 220, 255)
    eye_l = np.array([[220, 230], [270, 230], [245, 180]], np.int32)
    eye_r = np.array([[370, 230], [420, 230], [395, 180]], np.int32)
    cv2.fillPoly(img, [eye_l, eye_r], glow, cv2.LINE_AA)
    cv2.fillPoly(img, [np.array([[300, 280], [340, 280], [320, 250]], np.int32)], glow, cv2.LINE_AA)
    mouth = [(200, 320), (240, 350), (270, 330), (300, 360), (340, 360), (370, 330), (400, 350),
             (440, 320), (400, 390), (240, 390)]  # fmt: skip
    cv2.fillPoly(img, [np.array(mouth, np.int32)], glow, cv2.LINE_AA)
    return img


def snowflake() -> np.ndarray:
    """A six-armed snowflake on black, 480x480, drawn with lines."""
    img = np.zeros((480, 480, 3), np.uint8)
    c = (240, 240)
    color = (255, 235, 200)
    for k in range(6):
        a = math.pi / 3 * k
        end = (round(240 + 200 * math.cos(a)), round(240 + 200 * math.sin(a)))
        cv2.line(img, c, end, color, 10, cv2.LINE_AA)
        for r, length in ((90, 60), (150, 45)):
            bx, by = 240 + r * math.cos(a), 240 + r * math.sin(a)
            for side in (-1, 1):
                b = a + side * math.pi / 4
                tip = (round(bx + length * math.cos(b)), round(by + length * math.sin(b)))
                cv2.line(img, (round(bx), round(by)), tip, color, 8, cv2.LINE_AA)
    cv2.circle(img, c, 26, color, -1, cv2.LINE_AA)
    return img


def _gen(kind: str, **params: float | str) -> Generator:
    return Generator.model_validate({"type": kind, "params": params})


def _clip(
    surface: str, start_s: float, dur_s: float, *, gen: Generator | None = None,
    asset: str | None = None, fit: str = "fill", fade_s: float = 0.5, opacity: float = 1.0,
    blend: str = "normal",
) -> Clip:  # fmt: skip
    return Clip.model_validate(
        {
            "id": new_id("clip"), "asset_id": asset, "generator": gen, "surface_id": surface,
            "start_ms": round(start_s * 1000), "duration_ms": round(dur_s * 1000),
            "fit": fit, "opacity": opacity, "fade_in_ms": round(fade_s * 1000),
            "fade_out_ms": round(fade_s * 1000), "blend": blend,
        }
    )  # fmt: skip


def _tracks(theme: Theme, door: str, win_l: str, win_r: str, card: str, art: str) -> list[Track]:
    """The 12 s show. Each inner list is one track (bottom first); no overlaps on a track."""
    if theme == "halloween":
        layers = [
            [
                _clip(CANVAS, 0, 12, gen=_gen("rings", color_a="#200030", color_b="#000000",
                                              count=2, speed=0.2), opacity=0.5, fade_s=1),
            ],
            [
                _clip(door, 0, 3.5, asset=card, fit="fit", fade_s=0.4),
                _clip(door, 3.5, 8.5, gen=_gen("plasma", color_a="#ff5a00", color_b="#3a0060",
                                               scale=2.5, speed=0.6)),
            ],
            [
                _clip(win_l, 0, 12, gen=_gen("flicker", color="#ff9a20", rate_hz=2, depth=0.6,
                                             seed=3), fade_s=1),
            ],
            [
                _clip(win_r, 0, 12, gen=_gen("flicker", color="#ff9a20", rate_hz=1.5, depth=0.6,
                                             seed=8), fade_s=1),
            ],
            [_clip(door, 5, 5, asset=art, fit="fit", fade_s=0.8, blend="screen")],
            [
                _clip(door, 3.5, 8.5, gen=_gen("chase", color="#ff8000", width=0.05, dashes=18,
                                               speed=2), blend="add"),
            ],
        ]  # fmt: skip
    else:
        layers = [
            [
                _clip(CANVAS, 0, 12, gen=_gen("stars", color="#e0f0ff", density=14, size=0.3,
                                              twinkle_hz=0.5, seed=21), opacity=0.8, fade_s=1),
            ],
            [
                _clip(door, 0, 3.5, asset=card, fit="fit", fade_s=0.4),
                _clip(door, 3.5, 4.5, gen=_gen("cycle", period_s=6, spread=0.6, angle_deg=90,
                                               saturation=0.7, brightness=0.8)),
                _clip(door, 8, 4, gen=_gen("rings", color_a="#d01020", color_b="#10a040",
                                           count=3, speed=0.5)),
            ],
            [
                _clip(win_l, 0, 12, gen=_gen("sweep", color="#ffe0a0", width=0.3, period_s=3,
                                             angle_deg=90), fade_s=1),
            ],
            [
                _clip(win_r, 0, 12, gen=_gen("sweep", color="#ffe0a0", width=0.3, period_s=3,
                                             angle_deg=-90), fade_s=1),
            ],
            [_clip(door, 4, 4, asset=art, fit="fit", fade_s=0.8, blend="screen")],
            [
                _clip(door, 0, 12, gen=_gen("snow", color="#ffffff", density=9, size=0.3,
                                            speed=0.15, drift=0.4, seed=5), blend="add",
                      fade_s=1),
            ],
            [
                _clip(door, 3.5, 8.5, gen=_gen("chase", color="#ff2030", width=0.04, dashes=20,
                                               speed=1.5), blend="add"),
            ],
        ]  # fmt: skip
    return [
        Track(id=f"trk_{i + 1:08d}", name=f"Track {i + 1}", clips=clips)
        for i, clips in enumerate(layers)
    ]


def create_sample(
    folder: Path,
    project_id: str,
    theme: Theme = "halloween",
    *,
    name: str | None = None,
    progress: Progress | None = None,
    cancel: Cancel | None = None,
) -> Project:
    """Create a sample project in the empty or missing `folder` and return it (revision 0)."""
    if theme not in THEMES:
        raise FkError("BAD_REQUEST", f"theme: must be one of {', '.join(THEMES)}")
    report = progress or (lambda _f, _m: None)
    scene = default_scene()
    width, height = scene.proj_size
    folder.mkdir(parents=True, exist_ok=True)
    for sub in SUBFOLDERS:
        (folder / sub).mkdir(exist_ok=True)
    project = Project(
        id=project_id, name=name or sample_name(theme), revision=0,
        projector=ProjectorSpec(width=width, height=height, fps=30),
    )  # fmt: skip
    save_project_dir(folder, project)

    report(0.02, "Scanning the simulated house")
    display = SimDisplay(scene)
    cal = run_calibration(
        folder, display, SimCamera(scene, display), "sim",
        CalibSettings(discard_frames=0, average_frames=1),
        progress=lambda f, m: report(0.02 + 0.88 * f, f"Simulated scan: {m}"),
        cancel=cancel, sleep=lambda _s: None,
    )  # fmt: skip

    report(0.92, "Finding the door and windows")
    proj_view = cv2.imread(str(folder / "calibration" / cal.id / "proj_view.png"))
    if proj_view is None:
        raise FkError(INTERNAL, "The simulated scan has no projector view")
    door_quad = detect_door_quad(proj_view)

    def surface(sid: str, label: str, quad: list[Point], feather: float) -> Surface:
        return Surface(
            id=sid, name=label, quad=(quad[0], quad[1], quad[2], quad[3]),
            aspect=estimate_aspect(quad), feather_px=feather,
        )  # fmt: skip

    surfaces = [
        surface("srf_door0001", "Garage door", door_quad, 2.0),
        # The windows come from the simulated house's layout (it is a simulation).
        surface("srf_window01", "Left window", scene.feature_quad_proj("window_left"), 2.0),
        surface("srf_window02", "Right window", scene.feature_quad_proj("window_right"), 2.0),
    ]

    report(0.95, "Drawing the pictures")
    card = _write_png(folder, title_card(theme), "title-card.png")
    art_img = pumpkin() if theme == "halloween" else snowflake()
    art = _write_png(folder, art_img, "pumpkin.png" if theme == "halloween" else "snowflake.png")
    door, win_l, win_r = (s.id for s in surfaces)
    tracks = _tracks(theme, door, win_l, win_r, card.id, art.id)
    project = project.model_copy(
        update={
            "calibration_id": cal.id,
            "surfaces": surfaces,
            "assets": [card, art],
            "timeline": Timeline(duration_ms=SAMPLE_DURATION_MS, tracks=tracks),
        }
    )
    project = Project.model_validate(project.model_dump())  # runs the cross-checks
    save_project_dir(folder, project)
    report(1.0, "Sample ready")
    return project
